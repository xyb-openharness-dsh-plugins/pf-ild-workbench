-- 0004 · 演示数据元信息（只增不改：0001–0003 已冻结，本文件仅追加）
--
-- 为什么需要这张表：
--   试验匹配页要显示「规则集版本 / 生成时间 / 通道覆盖声明 / 免责文案」。
--   这些值原本只写在 `demo/build-demo-data.mjs` 的生成器里，而运行期的 `dsh/demo.js`
--   播种路径根本不会创建、也不会写入它们 —— 于是装机后打开页面，
--   读模型查 `demo_meta` 直接报 `no such table: demo_meta`。
--
--   这不是"演示用的临时表"：规则集版本决定"这一屏对照是按哪一版条目算的"，
--   用户看到「符合 3 / 冲突 1」时要能回答"按什么时候的标准"，所以它必须落库、可追溯，
--   而不是读模型里 new Date() 现场编一个。
--
-- 边界：只存"这份演示数据是怎么来的"这类元信息，不存任何患者事实。

CREATE TABLE IF NOT EXISTS demo_meta (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL
);
